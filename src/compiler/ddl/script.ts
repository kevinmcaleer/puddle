// A DBML schema as a script that creates it in a real database: schemas, enums, tables with their keys, defaults and
// checks, foreign keys after every table, indexes, notes as comments, and optionally the records. The parts every
// database shares are here; what differs (types, quoting, increments, enums, comments) comes from each dialect's rules
// (postgres.ts, mysql.ts, sqlserver.ts, sqlite.ts, and the DuckDB rules in duckdb.ts).
import { enumOf, qualified, type Column, type DbmlEnum, type DbmlSchema, type Default, type Ref, type RecordValue, type Table } from '../../schema';
import { identIn, strIn, type DdlDialect } from '../sql';
import { foreignKey, primaryKey } from './duckdb';
import { typeKind, type TypeKind } from './types';

/** What a column that increments is written as. */
export interface Increment {
  /** Its type, when the database needs a particular one (SQLite's INTEGER). */
  type?: string;
  /** What follows the type: `GENERATED BY DEFAULT AS IDENTITY`, `AUTO_INCREMENT`, `DEFAULT nextval(…)`. */
  clause: string;
  /** Statements that must come before the table (DuckDB's sequence). */
  before?: string[];
  /** The clause makes the column the primary key (SQLite), so the table doesn't name one. */
  primaryKey?: boolean;
}

/** How one database is written. */
export interface DialectRules {
  dialect: DdlDialect;
  label: string;
  /** The column type for a kind of type; undefined when the database has none (the type is written as given). */
  type: (t: TypeKind) => string | undefined;
  /** Types written as given that the database knows, beyond the common kinds (Postgres arrays, DuckDB's HUGEINT). */
  native?: (type: string) => boolean;
  /** Enums as types of their own, as `ENUM(…)` columns, or as text with a check on the values. */
  enums: 'type' | 'column' | 'check';
  /** The increment for a column of this type (already written for the database); undefined when it can't have one. */
  increment: (type: string, at: { table: Table; column: Column; tableRef: string; single: boolean }) => Increment | undefined;
  bool: (value: boolean) => string;
  /** Notes as `COMMENT ON` statements, as `COMMENT` clauses, or as `--` comments. */
  comments: 'comment-on' | 'clause' | 'lines';
  /**
   * Foreign keys inside CREATE TABLE, for a database that can't add them afterwards: SQLite takes them in any order;
   * DuckDB only to a table already created, never to the table itself, so a ref that closes a loop is left out.
   */
  inlineForeignKeys?: 'any-order' | 'parents-first';
  /** False where a foreign key can't point into another schema (DuckDB). */
  foreignKeysAcrossSchemas?: boolean;
  /** CREATE SCHEMA, and what follows it; `none` puts every table in the one namespace. */
  schemas: { create: (name: string) => string[] } | 'none';
  /** The ON DELETE and ON UPDATE actions it has. */
  actions: readonly string[];
}

export interface SqlScript {
  sql: string;
  /** Columns whose type the database has no word for: `table.column (type)`, written as given. */
  unmapped: string[];
  /** Anything else changed or left out, in a sentence each. */
  warnings: string[];
}

export interface ScriptOptions {
  /** INSERT statements for the records that aren't examples. */
  records?: boolean;
}

const NUMBER = /^[+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?$/i;

/** Many-to-many refs as a junction table between the two, as dbdiagram.io does: `a_b`, with a key of both sides. */
function withJunctions(schema: DbmlSchema): DbmlSchema {
  const many = schema.refs.filter((r) => r.op === '<>' && !r.inactive);
  if (!many.length) return schema;
  const tables = [...schema.tables];
  const refs: Ref[] = schema.refs.filter((r) => !many.includes(r));
  const taken = new Set(tables.map((t) => `${t.schema}.${t.name}`));
  for (const r of many) {
    const find = (e: Ref['from']) => tables.find((t) => t.schema === e.schema && t.name === e.table);
    const [a, b] = [find(r.from), find(r.to)];
    if (!a || !b) continue;
    let name = `${a.name}_${b.name}`;
    for (let i = 2; taken.has(`${a.schema}.${name}`); i++) name = `${a.name}_${b.name}_${i}`;
    taken.add(`${a.schema}.${name}`);
    const side = (t: Table, e: Ref['from']) => e.columns.map((c) => ({ from: `${t.name}_${c}`, to: c, type: t.columns.find((x) => x.name === c)?.type ?? 'integer' }));
    const [sa, sb] = [side(a, r.from), side(b, r.to)];
    const columns: Column[] = [...sa, ...sb].map((c) => ({ name: c.from, type: c.type, pk: false, unique: false, notNull: true, increment: false, checks: [], properties: {} }));
    tables.push({ schema: a.schema, name, columns, indexes: [{ parts: [...sa, ...sb].map((c) => ({ kind: 'column' as const, value: c.from })), pk: true, unique: false }], checks: [], properties: {}, partials: [] });
    const ref = (t: Table, s: typeof sa): Ref => ({ from: { schema: a.schema, table: name, columns: s.map((c) => c.from) }, to: { schema: t.schema, table: t.name, columns: s.map((c) => c.to) }, op: '>', fromOptional: false, toOptional: false, delete: r.delete, update: r.update, inactive: false, inline: false });
    refs.push(ref(a, sa), ref(b, sb));
  }
  return { ...schema, tables, refs };
}

/**
 * Parents before the tables whose foreign keys point at them; a loop keeps the order the tables are written in, and
 * the refs that close loops (a table's ref to itself among them) are given back.
 */
function ordered(schema: DbmlSchema): { tables: Table[]; loops: Set<Ref> } {
  const out: Table[] = [];
  const loops = new Set<Ref>();
  const state = new Map<Table, 'visiting' | 'done'>();
  const visit = (t: Table) => {
    if (state.has(t)) return;
    state.set(t, 'visiting');
    for (const r of schema.refs) {
      const fk = foreignKey(r);
      if (!fk || fk.child.schema !== t.schema || fk.child.table !== t.name) continue;
      const parent = schema.tables.find((x) => x.schema === fk.parent.schema && x.name === fk.parent.table);
      if (!parent) continue;
      if (parent === t || state.get(parent) === 'visiting') loops.add(r);
      else visit(parent);
    }
    state.set(t, 'done');
    out.push(t);
  };
  schema.tables.forEach(visit);
  return { tables: out, loops };
}

/** The statements that create a schema in a database, as one script. */
export function sqlScript(input: DbmlSchema, rules: DialectRules, options: ScriptOptions = {}): SqlScript {
  const schema = withJunctions(input);
  const q = (name: string) => identIn(rules.dialect, name);
  const s = (value: string) => strIn(rules.dialect, value);
  const unmapped: string[] = [];
  const warnings: string[] = [];
  const namespaces = rules.schemas !== 'none';
  const ref = (sch: string, name: string) => (sch === 'public' || !namespaces ? q(name) : `${q(sch)}.${q(name)}`);
  const enumRef = (e: DbmlEnum) => ref(e.schema, e.name);
  const out: string[] = [`-- ${rules.label} script made by Puddle from the project's DBML`];
  const block = (lines: string[]) => lines.length && out.push('', ...lines);

  if (!namespaces) {
    const other = [...new Set(schema.tables.filter((t) => t.schema !== 'public').map((t) => t.schema))];
    if (other.length) warnings.push(`${rules.label} has no schemas: the tables in ${other.join(', ')} are created without theirs.`);
  }
  const schemas = namespaces ? [...new Set([...schema.tables.map((t) => t.schema), ...(rules.enums === 'type' ? schema.enums.map((e) => e.schema) : [])])].filter((x) => x !== 'public') : [];
  if (rules.schemas !== 'none') block(schemas.flatMap((x) => (rules.schemas as Exclude<DialectRules['schemas'], 'none'>).create(q(x))));
  if (rules.enums === 'type') block(schema.enums.map((e) => `CREATE TYPE ${enumRef(e)} AS ENUM (${e.values.map((v) => s(v.name)).join(', ')});`));

  const bool = (v: string) => rules.bool(v.toLowerCase() === 'true');
  const defaultSql = (d: Default) => {
    switch (d.kind) {
      case 'string':
        return s(d.value);
      case 'number':
        return NUMBER.test(d.value) ? d.value : s(d.value);
      case 'boolean':
        return bool(d.value);
      case 'null':
        return 'NULL';
      case 'expression':
        return `(${d.value})`;
    }
  };
  const valueSql = (v: RecordValue) => {
    switch (v.kind) {
      case 'string':
        return s(v.value);
      case 'number':
        return NUMBER.test(v.value) ? v.value : s(v.value);
      case 'boolean':
        return bool(v.value);
      case 'null':
      case 'empty':
        return 'NULL';
      case 'expression':
        return v.value;
      case 'enum':
        return s(v.value.split('.').pop()!);
    }
  };
  const action = (a: string | undefined) => (a ? (rules.actions.includes(a) ? a.toUpperCase() : 'NO ACTION') : undefined);
  const fkSql = (r: Ref) => {
    const fk = foreignKey(r)!;
    const del = action(r.delete);
    const upd = action(r.update);
    const from = qualified(fk.child.schema, fk.child.table);
    if (r.delete && del !== r.delete.toUpperCase()) warnings.push(`${rules.label} has no ON DELETE ${r.delete.toUpperCase()}: the ref from ${from} uses NO ACTION.`);
    if (r.update && upd !== r.update.toUpperCase()) warnings.push(`${rules.label} has no ON UPDATE ${r.update.toUpperCase()}: the ref from ${from} uses NO ACTION.`);
    return `${r.name ? `CONSTRAINT ${q(r.name)} ` : ''}FOREIGN KEY (${fk.child.columns.map(q).join(', ')}) REFERENCES ${ref(fk.parent.schema, fk.parent.table)} (${fk.parent.columns.map(q).join(', ')})${del ? ` ON DELETE ${del}` : ''}${upd ? ` ON UPDATE ${upd}` : ''}`;
  };
  const oneLine = (text: string) => text.replace(/\s*\n\s*/g, ' ').trim();

  const columnType = (t: Table, c: Column): { type: string; check?: string } => {
    const e = enumOf(schema, c);
    if (e) {
      if (rules.enums === 'type') return { type: enumRef(e) };
      if (rules.enums === 'column') return { type: `ENUM(${e.values.map((v) => s(v.name)).join(', ')})` };
      const longest = Math.max(1, ...e.values.map((v) => v.name.length));
      return { type: rules.type({ kind: 'varchar', length: longest })!, check: `${q(c.name)} IN (${e.values.map((v) => s(v.name)).join(', ')})` };
    }
    const kind = typeKind(c.type);
    const written = kind && rules.type(kind);
    if (written) return { type: written };
    if (!rules.native?.(c.type)) unmapped.push(`${qualified(t.schema, t.name)}.${c.name} (${c.type})`);
    return { type: c.type };
  };

  const { tables, loops } = ordered(schema);
  const later: string[] = [];
  const comments: string[] = [];
  for (const t of tables) {
    const tableRef = ref(t.schema, t.name);
    const pk = primaryKey(t);
    let keyInline = false;
    const before: string[] = [];
    const lines: { text: string; note?: string }[] = t.columns.map((c) => {
      const { type, check } = columnType(t, c);
      const parts = [q(c.name), type];
      const inc = c.increment ? rules.increment(type, { table: t, column: c, tableRef, single: pk.length === 1 && pk[0] === c.name }) : undefined;
      if (c.increment && !inc) warnings.push(`${qualified(t.schema, t.name)}.${c.name} can’t increment in ${rules.label}: it is created without.`);
      if (inc) {
        if (inc.type) parts[1] = inc.type;
        if (inc.primaryKey) keyInline = true;
        before.push(...(inc.before ?? []));
        parts.push(inc.clause);
      } else if (c.default) parts.push(`DEFAULT ${defaultSql(c.default)}`);
      if (pk.length === 1 && pk[0] === c.name && !inc?.primaryKey) {
        parts.push('PRIMARY KEY');
        keyInline = true;
      } else if (c.notNull && !inc?.primaryKey) parts.push('NOT NULL');
      if (c.unique && !(pk.length === 1 && pk[0] === c.name)) parts.push('UNIQUE');
      for (const x of [...c.checks, ...(check ? [check] : [])]) parts.push(`CHECK (${x})`);
      if (c.note && rules.comments === 'clause') parts.push(`COMMENT ${s(oneLine(c.note))}`);
      return { text: parts.join(' '), note: rules.comments === 'lines' && c.note ? oneLine(c.note) : undefined };
    });
    if (pk.length && !keyInline) lines.push({ text: `PRIMARY KEY (${pk.map(q).join(', ')})` });
    for (const x of t.checks) lines.push({ text: `${x.name ? `CONSTRAINT ${q(x.name)} ` : ''}CHECK (${x.expression})` });
    const fks = schema.refs.filter((r) => {
      const fk = foreignKey(r);
      if (!fk || fk.child.schema !== t.schema || fk.child.table !== t.name || !schema.tables.some((x) => x.schema === fk.parent.schema && x.name === fk.parent.table)) return false;
      if (rules.foreignKeysAcrossSchemas === false && fk.parent.schema !== t.schema) {
        warnings.push(`The ref from ${qualified(t.schema, t.name)} to ${qualified(fk.parent.schema, fk.parent.table)} isn’t a foreign key in ${rules.label}: it can’t have one between schemas.`);
        return false;
      }
      if (rules.inlineForeignKeys === 'parents-first' && loops.has(r)) {
        warnings.push(`The ref from ${qualified(t.schema, t.name)} to ${qualified(fk.parent.schema, fk.parent.table)} isn’t a foreign key in ${rules.label}: it closes a loop of tables that refer to each other.`);
        return false;
      }
      return true;
    });
    if (rules.inlineForeignKeys) for (const r of fks) lines.push({ text: fkSql(r) });
    else for (const r of fks) later.push(`ALTER TABLE ${tableRef} ADD ${fkSql(r)};`);

    const head = rules.comments === 'lines' && t.note ? t.note.split('\n').map((l) => `-- ${l.trim()}`) : [];
    const body = lines.map((l, i) => `  ${l.text}${i < lines.length - 1 ? ',' : ''}${l.note ? ` -- ${l.note}` : ''}`);
    const tail = rules.comments === 'clause' && t.note ? `) COMMENT=${s(oneLine(t.note))};` : ');';
    block([...before, ...head, `CREATE TABLE ${tableRef} (`, ...body, tail]);

    const indexes = t.indexes.flatMap((ix, i) => {
      if (ix.pk) return [];
      const parts = ix.parts.map((p) => (p.kind === 'column' ? q(p.value) : p.value));
      return [`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${q(ix.name ?? `${t.name}_index_${i + 1}`)} ON ${tableRef} (${parts.join(', ')});`];
    });
    block(indexes);
    if (rules.comments === 'comment-on') {
      if (t.note) comments.push(`COMMENT ON TABLE ${tableRef} IS ${s(t.note)};`);
      for (const c of t.columns) if (c.note) comments.push(`COMMENT ON COLUMN ${tableRef}.${q(c.name)} IS ${s(c.note)};`);
    }
  }
  block(later);
  block(comments);

  if (options.records)
    for (const t of tables) {
      const blocks = schema.records.filter((r) => r.schema === t.schema && r.table === t.name && !r.example && r.rows.length);
      for (const b of blocks) {
        const columns = b.columns.filter((c) => t.columns.some((x) => x.name === c));
        const rows = b.rows.map((row) => `  (${columns.map((c) => valueSql(row[b.columns.indexOf(c)] ?? { kind: 'null', value: '' })).join(', ')})`);
        block([`INSERT INTO ${ref(t.schema, t.name)} (${columns.map(q).join(', ')}) VALUES`, `${rows.join(',\n')};`]);
      }
    }

  return { sql: `${out.join('\n')}\n`, unmapped: [...new Set(unmapped)], warnings: [...new Set(warnings)] };
}
