// How a schema is written for PostgreSQL: its own enum types, identity columns and COMMENT ON.
import type { DialectRules } from './script';
import { decimalArgs, type TypeKind } from './types';

const INT = { 1: 'smallint', 2: 'smallint', 4: 'integer', 8: 'bigint' } as const;

export const POSTGRES: DialectRules = {
  dialect: 'postgres',
  label: 'PostgreSQL',
  type: (t: TypeKind) => {
    switch (t.kind) {
      case 'varchar':
        return t.length ? `varchar(${t.length})` : 'varchar';
      case 'char':
        return `char(${t.length ?? 1})`;
      case 'int':
        return INT[t.bytes];
      case 'decimal':
        return `numeric${decimalArgs(t)}`;
      case 'float':
        return 'real';
      case 'double':
        return 'double precision';
      case 'blob':
        return 'bytea';
      case 'json':
        return 'jsonb';
      default:
        return t.kind;
    }
  },
  // Arrays of any type it knows, and the rest of its own types.
  native: (type) => /\[\d*\]$/.test(type) || /^(inet|cidr|macaddr|tsvector|point|xml|money|citext|hstore|bit varying.*|varbit.*)$/i.test(type),
  enums: 'type',
  increment: (type) => (/^(smallint|integer|bigint)$/.test(type) ? { clause: 'GENERATED BY DEFAULT AS IDENTITY' } : undefined),
  bool: (v) => (v ? 'true' : 'false'),
  comments: 'comment-on',
  schemas: { create: (name) => [`CREATE SCHEMA IF NOT EXISTS ${name};`] },
  actions: ['cascade', 'restrict', 'set null', 'set default', 'no action'],
};
