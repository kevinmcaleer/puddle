import { expect, test } from '@playwright/test';
import { openApp } from './helpers/app';

const DBML = `Table customers {
  id integer [pk, increment]
  email varchar(255) [not null, unique]
}

Table orders {
  id integer [pk, increment]
  customer_id integer
  search tsvector
}

Ref: orders.customer_id > customers.id [delete: cascade]
`;

test('exporting the schema as SQL: pick a database, see the script and its notice, download schema.sql', async ({ page }) => {
  await openApp(page);
  await page.getByTestId('project-menu').click();
  await page.getByRole('menuitem', { name: 'Schema' }).click();
  await page.getByRole('combobox', { name: 'DBML' }).fill(DBML);
  await expect(page.getByTestId('schema-table-orders')).toBeVisible();

  await page.getByRole('button', { name: 'Export' }).click();
  await page.getByRole('menuitem', { name: /SQL/ }).click();
  const dialog = page.getByRole('dialog', { name: 'Export as SQL' });
  const preview = dialog.getByTestId('export-sql-preview');
  await expect(preview).toContainText('"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');

  // SQL Server writes its own types and increments, and says which type it has no word for.
  await dialog.getByLabel('Database').selectOption({ label: 'SQL Server' });
  await expect(preview).toContainText('[email] nvarchar(255) NOT NULL UNIQUE');
  await expect(preview).toContainText('[id] int IDENTITY(1,1) PRIMARY KEY');
  await expect(dialog.getByTestId('export-sql-notes')).toContainText('orders.search (tsvector)');

  const download = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download schema.sql' }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe('schema.sql');
  const sql = Buffer.concat(await (await file.createReadStream()).toArray()).toString('utf8');
  expect(sql).toContain('ALTER TABLE [orders] ADD FOREIGN KEY ([customer_id]) REFERENCES [customers] ([id]) ON DELETE CASCADE;');
  await expect(dialog).toHaveCount(0);
});
